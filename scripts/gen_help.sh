#!/bin/sh
# Turn the help pages (src/cli/help/**/*.txt) into C data compiled into the
# binary: one array of line strings per page, and a table of the pages by
# name ("overview", "guides/tui", "commands/send", ...). Why: the pages stay
# plain text in the repository, readable and linkable on GitHub, and callbox
# still prints them with no file I/O at run time. One string per line keeps
# every literal far below the 4095 characters C99 promises.
#
# usage: scripts/gen_help.sh <root> <file.txt>... > gen/help_text.c
# POSIX sh and awk only, so every release build (macOS, cross compilers) can
# run it.
set -eu
root=$1
shift

echo '/* Generated by scripts/gen_help.sh from src/cli/help: do not edit. */'
echo '#include "callbox/help_text.h"'
echo '#include <stddef.h>'
echo

n=0
names=""
for f in "$@"; do
    awk -v idx="$n" '
    BEGIN { printf "static const char *const page_%d[] = {\n", idx }
    {
        line = $0
        gsub(/\\/, "\\\\", line)
        gsub(/"/, "\\\"", line)
        gsub(/\t/, "\\t", line)
        gsub(/\?\?/, "?\\?", line) # no trigraphs in strict C
        printf "    \"%s\\n\",\n", line
    }
    END { print "    NULL,"; print "};"; print "" }
    ' "$f"
    name=${f#"$root"/}
    name=${name%.txt}
    names="$names $n:$name"
    n=$((n + 1))
done

echo 'const struct hold_help_page hold_help_pages[] = {'
for entry in $names; do
    printf '    {"%s", page_%s},\n' "${entry#*:}" "${entry%%:*}"
done
echo '    {NULL, NULL},'
echo '};'
